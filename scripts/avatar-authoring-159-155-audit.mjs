import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createFrameProject,replaceFrameSlot,updateFramePatch,frameProjectProgress,applyPinchFromPointers} from '../src/creators/avatar/avatar-frame-project.mjs';
import {createAlphaEditMask,brushErase,encodeMaskRuns,decodeMaskRuns} from '../src/creators/avatar/avatar-frame-pixels.mjs';
import {createAvatarWorkspaceManifest} from '../src/creators/workspaces/avatar-workspace.mjs';

const project=createFrameProject({id:'integration-audit',now:1});
assert.equal(project.slots.length,16);
assert.deepEqual(project.runtimeContract.directionKeys,['s','w','e','n']);
assert.deepEqual({width:project.frameCanvas.width,height:project.frameCanvas.height,mode:project.frameCanvas.mode},{width:128,height:192,mode:'contain'});
assert.equal(project.frameCanvas.pixelArt,true);
let next=replaceFrameSlot(project,0,{sourceKey:'frame-0',sourceName:'0.png',sourceWidth:64,sourceHeight:96});
next=updateFramePatch(next,0,{scale:1.25,x:4,y:-2},{state:'VALID'});
assert.equal(frameProjectProgress(next).present,1);
assert.equal(next.slots[0].patch.scale,1.25);
const pinched=applyPinchFromPointers(next.slots[0].patch,{a0:{x:0,y:0},b0:{x:10,y:0},a1:{x:2,y:3},b1:{x:22,y:3}});
assert.ok(pinched.scale>next.slots[0].patch.scale);
const mask=createAlphaEditMask(16,16),erased=brushErase(mask,16,16,8,8,{radius:3}).mask,encoded=encodeMaskRuns(erased),decoded=decodeMaskRuns(encoded,16,16);
assert.deepEqual([...decoded],[...erased]);
const surgerySession={shell:{isConnected:true}};let warned=false;
const resilientManifest=createAvatarWorkspaceManifest({loader:async()=>({openAvatarQuickImport:async()=>surgerySession}),authoringLoader:async()=>{throw new Error('EXPECTED_EXTENSION_FAILURE');}});
const fallbackSession=await resilientManifest.open({root:{console:{warn(){warned=true;}}}});
assert.equal(fallbackSession,surgerySession,'Frame Surgery must stay usable if the 4x4 extension fails to load');
assert.equal(warned,true);
const authoring=fs.readFileSync('src/creators/ui/avatar-authoring-workspace.mjs','utf8');
const builder=fs.readFileSync('src/creators/ui/avatar-frame-builder.mjs','utf8');
const manifest=fs.readFileSync('src/creators/workspaces/avatar-workspace.mjs','utf8');
assert.ok(authoring.includes('CONSTRUIR 4×4 · FRAME A FRAME'));
assert.ok(authoring.includes('attachFrameBuilderToSurgery'));
assert.ok(authoring.includes('openAvatarFrameBuilder'));
assert.ok(builder.includes('exactCanvas:spec'));
assert.ok(builder.includes('ATLAS ${spec.width*4}×${spec.height*4}'));
assert.ok(manifest.includes("avatar-frame-surgery-workspace.mjs"));
assert.ok(manifest.includes("avatar-authoring-workspace.mjs"));
assert.ok(manifest.includes('attachFrameBuilderToSurgery'));
console.log('✓ PR 159 Frame Surgery remains the direct authoritative workspace route');
console.log('✓ PR 155 persistent 4x4 builder is attached after Frame Surgery opens');
console.log('✓ Frame Surgery remains usable if the PR 155 extension cannot load');
console.log('✓ builder targets exact 128×192 frames / 512×768 4×4 atlas');
console.log('✓ 4x4 project, gesture math and non-destructive masks behave');
