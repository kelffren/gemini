'use strict';
const assert=require('node:assert/strict');
const {installPvpPresentationWire,presentationKey}=require('./pvp-presentation-wire');
class FakeSocket{constructor(){this.sent=[];}send(data){this.sent.push(JSON.parse(String(data)));}}
const api=installPvpPresentationWire({WebSocket:FakeSocket});
const socket=new FakeSocket();
const modular=(revisionKey,revisionId='11111111-1111-4111-8111-111111111111')=>({revisionId,contentId:'creator:hero',source:'server-authoritative-presentation',creatorAppearance:{source:'server-authoritative-published',revisionKey,loadout:[]}});
const r3=modular('weaponMain:33333333-3333-4333-8333-333333333333');
const r4=modular('weaponMain:44444444-4444-4444-8444-444444444444');
assert.equal(presentationKey(r3),presentationKey(JSON.parse(JSON.stringify(r3))),'key must be deterministic');
assert.notEqual(presentationKey(r3),presentationKey(r4),'revision change must change key');
socket.send(JSON.stringify({t:'welcome',id:'p1',players:{p1:{id:'p1',zone:'plaza',avatarManifest:null},p2:{id:'p2',zone:'plaza',avatarManifest:r3},p3:{id:'p3',zone:'plaza',avatarManifest:null}}}));
socket.sent=[];
socket.send(JSON.stringify({t:'pvp:snapshot',serverTime:10,players:{p1:{id:'p1',zone:'pvp'},p2:{id:'p2',zone:'pvp'},p3:{id:'p3',zone:'pvp'}}}));
assert.equal(socket.sent.filter(x=>x.t==='pvp:presentation').length,1,'only real first presentation is sent');
assert.equal(socket.sent.at(-1).t,'pvp:snapshot','presentation precedes competitive snapshot');
assert.equal(socket.sent.at(-1).players.p2.presentationKey,presentationKey(r3));
assert.equal(socket.sent.at(-1).players.p3.presentationKey,null,'empty presentation uses null key without extra packet');
socket.sent=[];
socket.send(JSON.stringify({t:'pvp:snapshot',serverTime:20,players:{p1:{id:'p1',zone:'pvp'},p2:{id:'p2',zone:'pvp'},p3:{id:'p3',zone:'pvp'}}}));
assert.equal(socket.sent.filter(x=>x.t==='pvp:presentation').length,0,'unchanged presentation not resent');
socket.sent=[];
socket.send(JSON.stringify({t:'state',serverTime:30,players:{p1:{id:'p1',zone:'pvp',avatarManifest:null},p2:{id:'p2',zone:'pvp',avatarManifest:r4},p3:{id:'p3',zone:'pvp',avatarManifest:null}}}));
const presentation=socket.sent.find(x=>x.t==='pvp:presentation');const state=socket.sent.find(x=>x.t==='state');
assert.ok(presentation,'changed presentation must be sent');assert.equal(presentation.presentationKey,presentationKey(r4));
assert.equal(Object.hasOwn(state.players.p2,'avatarManifest'),false,'heavy manifest stripped from redundant PvP social state');
assert.equal(state.players.p2.presentationKey,presentationKey(r4));
socket.sent=[];
socket.send(JSON.stringify({t:'state',serverTime:40,players:{p1:{id:'p1',zone:'pvp',avatarManifest:null},p2:{id:'p2',zone:'pvp',avatarManifest:null}}}));
assert.equal(socket.sent.find(x=>x.t==='pvp:presentation').avatarManifest,null,'clear presentation is propagated once after a real visual');
socket.sent=[];
socket.send(JSON.stringify({t:'state',serverTime:45,players:{p1:{id:'p1',zone:'pvp',avatarManifest:null},p2:{id:'p2',zone:'pvp',avatarManifest:r4}}}));
assert.equal(socket.sent.filter(x=>x.t==='pvp:presentation').length,1,'real visual can return after clear');
socket.sent=[];
socket.send(JSON.stringify({t:'pvp:snapshot',serverTime:50,players:{p1:{id:'p1',zone:'pvp'}}}));
socket.send(JSON.stringify({t:'pvp:snapshot',serverTime:60,players:{p1:{id:'p1',zone:'pvp'},p2:{id:'p2',zone:'pvp'}}}));
assert.equal(socket.sent.filter(x=>x.t==='pvp:presentation').length,1,'re-entering visibility resends current real presentation after prune');
const audit=api.audit();assert.equal(audit.sameSocket,true);assert.equal(audit.fullManifestEverySnapshot,false);
console.log('PASS pvp presentation wire smoke',audit);
